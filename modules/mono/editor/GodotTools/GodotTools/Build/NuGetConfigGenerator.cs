using System;
using System.IO;
using System.Text;
using System.Xml;
using Godot;
using GodotTools.Internals;

namespace GodotTools.Build
{
    /// <summary>
    /// Generates a <c>NuGet.Config</c> in the Godot project root that points NuGet at the
    /// packages bundled with this editor build (under <c>&lt;editor&gt;/GodotSharp/Tools/nupkgs</c>).
    ///
    /// This is required for custom engine builds: the bundled GodotSharp/Godot.NET.Sdk packages
    /// use a version that doesn't exist on nuget.org, so without a source pointing at the bundled
    /// folder, NuGet's SDK resolver and restore would fail to find them. The config clears inherited
    /// sources, adds the bundled package folder plus nuget.org, then uses package source mapping so
    /// Godot packages are restored only from the editor bundle while ordinary third-party packages
    /// can still restore from nuget.org.
    ///
    /// The file is rewritten on every build using the current editor's absolute path, so it stays
    /// correct across machines and editor relocations. It is expected to be gitignored in the
    /// game repository (the path is machine-local).
    /// </summary>
    public static class NuGetConfigGenerator
    {
        private const string NuGetConfigFileName = "NuGet.Config";
        private const string BundledSourceKey = "GodotBundled";
        private const string NuGetOrgSourceKey = "nuget.org";
        private const string NuGetOrgSourceUrl = "https://api.nuget.org/v3/index.json";

        private static readonly string[] BundledPackageIds =
        {
            "Godot.NET.Sdk",
            "Godot.SourceGenerators",
            "GodotSharp",
            "GodotSharpEditor",
        };

        /// <summary>
        /// Resolves the absolute path to the bundled nupkgs folder shipped next to the editor,
        /// or <see langword="null"/> if it cannot be found (e.g. running from a source tree
        /// where assemblies were not packed).
        /// </summary>
        private static string? GetBundledNupkgsDir()
        {
            // DataEditorToolsDir resolves to "<editor_dir>/GodotSharp/Tools" (with platform-specific
            // fallbacks handled on the C++ side, e.g. inside the .app bundle on macOS).
            string toolsDir = GodotSharpDirs.DataEditorToolsDir;
            if (string.IsNullOrEmpty(toolsDir))
                return null;

            string nupkgsDir = Path.Combine(toolsDir, "nupkgs");
            return Directory.Exists(nupkgsDir) ? nupkgsDir : null;
        }

        /// <summary>
        /// Writes/refreshes the <c>NuGet.Config</c> in the given project directory so it points at
        /// the bundled nupkgs folder. No-op (returns <see langword="false"/>) if the bundled folder
        /// can't be located, leaving any existing user configuration untouched.
        /// </summary>
        public static bool Generate(string projectDir)
        {
            if (string.IsNullOrEmpty(projectDir))
                return false;

            string? nupkgsDir = GetBundledNupkgsDir();
            if (nupkgsDir == null)
            {
                if (Godot.OS.IsStdOutVerbose())
                    GD.Print("NuGetConfigGenerator: bundled nupkgs folder not found, skipping NuGet.Config generation.");
                return false;
            }

            string configPath = Path.Combine(projectDir, NuGetConfigFileName);

            try
            {
                var settings = new XmlWriterSettings
                {
                    Encoding = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false),
                    Indent = true,
                    IndentChars = "  ",
                    NewLineChars = "\n",
                };

                using (XmlWriter writer = XmlWriter.Create(configPath, settings))
                {
                    writer.WriteStartDocument();
                    writer.WriteComment(
                        "\n" +
                        "  Auto-generated by the Godot editor for this custom engine build.\n" +
                        "  Locks Godot packages to the nupkgs bundled with this editor.\n" +
                        "  This file is machine-local (absolute path below) and should be gitignored.\n" +
                        "  It is rewritten on every build; manual edits will be lost.\n"
                    );
                    writer.WriteStartElement("configuration");
                    writer.WriteStartElement("packageSources");
                    writer.WriteStartElement("clear");
                    writer.WriteEndElement();
                    writer.WriteStartElement("add");
                    writer.WriteAttributeString("key", BundledSourceKey);
                    writer.WriteAttributeString("value", nupkgsDir);
                    writer.WriteEndElement();
                    writer.WriteStartElement("add");
                    writer.WriteAttributeString("key", NuGetOrgSourceKey);
                    writer.WriteAttributeString("value", NuGetOrgSourceUrl);
                    writer.WriteAttributeString("protocolVersion", "3");
                    writer.WriteEndElement();
                    writer.WriteEndElement();
                    writer.WriteStartElement("packageSourceMapping");
                    writer.WriteStartElement("clear");
                    writer.WriteEndElement();
                    writer.WriteStartElement("packageSource");
                    writer.WriteAttributeString("key", BundledSourceKey);
                    foreach (string packageId in BundledPackageIds)
                    {
                        writer.WriteStartElement("package");
                        writer.WriteAttributeString("pattern", packageId);
                        writer.WriteEndElement();
                    }
                    writer.WriteEndElement();
                    writer.WriteStartElement("packageSource");
                    writer.WriteAttributeString("key", NuGetOrgSourceKey);
                    writer.WriteStartElement("package");
                    writer.WriteAttributeString("pattern", "*");
                    writer.WriteEndElement();
                    writer.WriteEndElement();
                    writer.WriteEndElement();
                    writer.WriteEndElement();
                    writer.WriteEndDocument();
                }

                if (Godot.OS.IsStdOutVerbose())
                    GD.Print($"NuGetConfigGenerator: wrote {configPath} pointing at {nupkgsDir}");

                return true;
            }
            catch (Exception e)
            {
                GD.PushError($"NuGetConfigGenerator: failed to write {configPath}: {e.Message}");
                return false;
            }
        }

        /// <summary>
        /// Writes/refreshes <c>NuGet.Config</c> next to the solution used by a build or publish.
        /// </summary>
        public static bool GenerateForBuild(BuildInfo buildInfo)
        {
            string? solutionDir = Path.GetDirectoryName(buildInfo.Solution);
            return solutionDir != null && Generate(solutionDir);
        }
    }
}
